// Emits src/EmpireSim.Core/Models/WorldGeometry.Data.cs from out/geometry.json. usage: node emit.js <out.cs> [version]
'use strict';
const fs = require('fs');
const L = require('./lib');
const PATHS = require('./paths');
const { W, H } = L;
const outFile = process.argv[2];
const version = parseInt(process.argv[3] || '2', 10);
const g = JSON.parse(fs.readFileSync(PATHS.out('geometry.json'), 'utf8'));
const caps = JSON.parse(fs.readFileSync(PATHS.out('geometry.capitals.json'), 'utf8'));
const world = PATHS.world();
const lab = new Int16Array(fs.readFileSync(PATHS.out('labels.bin')).buffer.slice(0));
const ownerIds = JSON.parse(fs.readFileSync(PATHS.out('labels.owners.json'), 'utf8'));

// ---- label point: the spot deepest inside the owner's biggest piece (so a region's name sits on it, not in the sea)
function labelPoint(id) {
  const v = ownerIds.indexOf(id) + 1; if (!v) return null;
  const mask = new Uint8Array(W * H); let any = false;
  for (let i = 0; i < mask.length; i++) if (lab[i] === v) { mask[i] = 1; any = true; }
  if (!any) return null;
  const c = L.components(mask, i => mask[i] === 1); let best = 0, bs = -1; for (let k = 1; k <= c.count; k++) if (c.sizes[k] > bs) { bs = c.sizes[k]; best = k; }
  let x0 = W, y0 = H, x1 = 0, y1 = 0; for (let i = 0; i < mask.length; i++) if (c.comp[i] === best) { const x = i % W, y = (i / W) | 0; x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y); }
  const w = x1 - x0 + 3, h = y1 - y0 + 3, d = new Float32Array(w * h).fill(1e9);
  const inside = (x, y) => (x >= x0 && x <= x1 && y >= y0 && y <= y1) && c.comp[y * W + x] === best;
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) if (!inside(x + x0 - 1, y + y0 - 1)) d[y * w + x] = 0;
  for (let y = 1; y < h; y++) for (let x = 1; x < w - 1; x++) { const i = y * w + x; d[i] = Math.min(d[i], d[i - 1] + 1, d[i - w] + 1, d[i - w - 1] + 1.4, d[i - w + 1] + 1.4); }
  for (let y = h - 2; y >= 0; y--) for (let x = w - 2; x >= 1; x--) { const i = y * w + x; d[i] = Math.min(d[i], d[i + 1] + 1, d[i + w] + 1, d[i + w + 1] + 1.4, d[i + w - 1] + 1.4); }
  let bi = 0, bv = -1; for (let i = 0; i < d.length; i++) if (d[i] > bv && d[i] < 1e8) { bv = d[i]; bi = i; }
  return [x0 - 1 + (bi % w), y0 - 1 + ((bi / w) | 0)];
}

const enc = rings => rings.map(r => r.map(p => p[0].toFixed(1) + ',' + p[1].toFixed(1)).join(' ')).join(';');
const lines = [];
const P = s => lines.push(s);
P('// <auto-generated>');
P('// Generated by tools/mapgen (node build.js, then node emit.js). Do not edit by hand: change the claims in tools/mapgen/regions and regenerate.');
P('// </auto-generated>');
P('namespace EmpireSim.Core.Models;');
P('');
P('/// <summary>');
P('/// Data half of <see cref="WorldGeometry"/> (the code half is in WorldGeometry.cs). The political map of the 1600 world: one planar partition of the land of world-terrain.jpg (2200 x 1150 map units).');
P('/// Coastlines are the terrain image\'s own; every border between two realms is the SAME list of points in both realms\' polygons,');
P('/// so neighbours meet exactly (no gaps, no overlaps). A realm with an enclave or an inner sea has that hole joined to its outline by a');
P('/// zero-width bridge, so each polygon is still one plain list of points. Rings are closed (the last point repeats the first).');
P('/// </summary>');
P('public static partial class WorldGeometry');
P('{');
P('    /// <summary>Bumped whenever the polygons change; a save made under an older version has its map refreshed on load (see <see cref="Upgrade"/>).</summary>');
P(`    public const int Version = ${version};`);
P('');
P('    private static readonly Dictionary<string, string> Nations = new()');
P('    {');
for (const n of world.nations) P(`        ["${n.id}"] = "${enc(g.geometry[n.id] || [])}",`);
P('    };');
P('');
// neutral territories that still have land (a few were carved entirely into colony regions) and every colonisable region (the three open-sea archipelagos first)
const neutralNames = g.owners.filter(o => o.kind === 'neutral' && (g.geometry[o.id] || []).length > 0).map(o => o.name);
const frontierNames = g.owners.filter(o => o.kind === 'frontier').map(o => o.name);
P('    private static readonly Dictionary<string, string> Neutrals = new()');
P('    {');
for (const nm of neutralNames) P(`        ["${nm}"] = "${enc(g.geometry['n:' + nm] || [])}",`);
P('    };');
P('');
P('    private static readonly Dictionary<string, string> Frontiers = new()');
P('    {');
for (const nm of frontierNames) P(`        ["${nm}"] = "${enc(g.geometry['f:' + nm] || [])}",`);
P('    };');
P('');
P('    /// <summary>Where each neutral / frontier region\'s name is written: the point deepest inside its biggest piece.</summary>');
P('    private static readonly Dictionary<string, (double X, double Y)> Labels = new()');
P('    {');
const labels = {};
for (const nm of neutralNames) { const p = labelPoint('n:' + nm); if (p) { labels[nm] = p; P(`        ["${nm}"] = (${p[0]}, ${p[1]}),`); } }
for (const nm of frontierNames) { const p = labelPoint('f:' + nm); if (p) { labels[nm] = p; P(`        ["${nm}"] = (${p[0]}, ${p[1]}),`); } }
P('    };');
P('');
P('    /// <summary>Capitals that were moved onto their own land (a harbour town the coast had put in the sea, or a capital that lay in another realm).</summary>');
P('    public static readonly IReadOnlyDictionary<string, (string Name, double X, double Y, double WasX, double WasY)> Capitals = new Dictionary<string, (string Name, double X, double Y, double WasX, double WasY)>');
P('    {');
for (const n of world.nations) { const c = caps[n.id]; if (c.note) P(`        ["${n.id}"] = ("${c.name}", ${c.x}, ${c.y}, ${c.was[0]}, ${c.was[1]}),   // ${c.note}`); }
P('    };');
P('');
const painted = JSON.parse(fs.readFileSync(PATHS.out('geometry.painted.json'), 'utf8')).filter(id => !id.startsWith('f:'));
P('    /// <summary>Countries whose islands are painted onto the open sea by the map (the terrain image has no land there), so the renderer gives them a land base and a coast of their own.</summary>');
P('    private static readonly HashSet<string> PaintedNations = new() { ' + painted.map(id => `"${id}"`).join(', ') + ' };');
P('');
P('    public static IReadOnlyList<string> NeutralNames { get; } = new[] { ' + neutralNames.map(n => `"${n}"`).join(', ') + ' };');
P('');
P('    /// <summary>Every colonisable region, in a fixed order: the open-sea archipelagos first, then the regions carved out of neutral land.</summary>');
P('    public static IReadOnlyList<string> FrontierNames { get; } = new[] { ' + frontierNames.map(n => `"${n}"`).join(', ') + ' };');
P('}');
fs.writeFileSync(outFile, lines.join('\r\n') + '\r\n');
fs.writeFileSync(PATHS.out('labels.out.json'), JSON.stringify(labels));
console.log('wrote', outFile, (fs.statSync(outFile).size / 1024).toFixed(0) + ' KB');
